def _prop(
    value: Any,
    unit: str,
    evidence: str,
    source: str,
    url: str = "https://www.usgs.gov/centers/astrogeology-science-center/data",
    method: str = "Direct field survey / published literature",
    confidence: Optional[float] = 0.90,
) -> Dict[str, Any]:
    """Helper to build a scientifically traceable property object (Section 7)."""
    if value is None:
        evidence = "UNKNOWN"
        confidence = None
    return {
        "value": value,
        "unit": unit,
        "evidence": evidence,
        "source": source,
        "url": url,
        "method": method,
        "confidence": confidence,
    }


