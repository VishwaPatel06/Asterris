def build_subsurface_catalog(existing_candidates: Optional[List[Dict[str, Any]]] = None) -> List[Dict[str, Any]]:
    """Merges the 15 richly documented terrestrial subsurface sites with any existing seed or DEM-discovered cave records.

    Ensures 100% backward compatibility with `ctx["cand_list"]` and `st.session_state["discovered"]`
    while strictly labelling derived/demonstration properties as `DERIVED`, `INFERRED`, `DEMONSTRATION`, or `UNKNOWN`.
    """
    records: List[Dict[str, Any]] = [dict(s) for s in TERRESTRIAL_SUBSURFACE_SITES]
    known_coords = [(s["lat"], s["lon"]) for s in TERRESTRIAL_SUBSURFACE_SITES]

    if existing_candidates:
        for c in existing_candidates:
            # Include any candidate from ctx["cand_list"] that has cave potential or is a discovered pit chain
            is_cave = (c.get("caves") or 0) >= 0.45 or c.get("morphology") in ("lava_tube", "pit_chain") or c.get("scale") == "cave"
            if not is_cave:
                continue

            clat, clon = float(c.get("lat", 0.0)), float(c.get("lon", 0.0))
